// Precompute derived/index fields (nameKey, ownership/category defaults).
export const SEED_COMPANY_RECORDS: Partial<ICompany>[] = companies.map((c) => {
  const nameKey = toNameKey(c.displayName);
  const searchableAliases = (c.aliases || []).filter(Boolean);
  const officialDomains = (c.officialDomains || []).filter(Boolean);
  if (c.website && !officialDomains.includes(c.website)) {
    try {
      const host = new URL(c.website).hostname;
      if (!officialDomains.includes(host)) officialDomains.push(host);
    } catch {
      // ignore invalid URL
    }
  }
  const dataSources = (c.dataSources || []).concat(c.officialSources || []).filter(Boolean);
  return {
    ...c,
    nameKey,
    aliases: searchableAliases,
    industries: c.industries || (c.industry ? [c.industry] : []),
    countries: c.countries || (c.headquarters?.country ? [c.headquarters.country] : []),
    regions: c.regions || (c.headquarters?.region ? [c.headquarters.region] : []),
    products: c.products || [],
    founders: c.founders || [],
    subsidiaries: c.subsidiaries || [],
    leadership: c.leadership || [],
    socialLinks: c.socialLinks || {},
    officialSources: c.officialSources || [],
    dataSources,
    sourceUrls: (dataSources as Array<{ url?: string }>).map((s) => s.url || '').filter(Boolean),
    sourceDates: (dataSources as Array<{ retrievedAt?: Date }>).map((s) => s.retrievedAt || new Date()).filter(Boolean),
    lastVerifiedAt: new Date(),
    officialDomains,
    technologies: c.technologies || [],
    services: c.services || [],
    competitors: c.competitors || [],
    brands: c.brands || [],
    acquisitions: c.acquisitions || [],
    investments: c.investments || [],
    partners: c.partners || [],
  };
});
